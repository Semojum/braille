"""#1507 — 한 자리 문항 번호 뒤에 문항 코드가 오면 원본에 없는 마침표를 만들어 넣지 않는다(원장 C-41 부록7).

「점자 자료 제작 지침」 4.2.2(4)(재추출 2329행) · 「점자 도서 제작 지침」 3장 3절 2. 2)(5)(2993행):
지시문 · 발문의 번호와 문장 부호는 원본 자료에 따라 적는다. 묵자 문항 머리에는 마침표가 없다.
기대 점자는 손으로 옮겼다: 8 ⠼⠓ · 빈칸 ⠀ · [ ⠦⠆ · 26900 ⠼⠃⠋⠊⠚⠚ · - ⠤ · 0050 ⠼⠚⠚⠑⠚ · ] ⠰⠴. 문항 코드는 지어낸 것이다.
"""
from semojum_braille.encoder.translator import translate_body


def _b(text: str) -> str:
    return "\n".join(translate_body(text)[0])


def test_문항_코드가_따라오면_마침표를_안_붙인다():
    assert _b("8 [26900-0050]") == "⠼⠓⠀⠦⠆⠼⠃⠋⠊⠚⠚⠤⠼⠚⠚⠑⠚⠰⠴"
    assert _b("1 [26900-0001] 다음 설명으로 옳은 것은?").startswith("⠼⠁⠀⠦⠆")
    assert _b("8 (26900-0050) 다음 설명으로 옳은 것은?").startswith("⠼⠓⠀⠦⠄")


def test_문항_코드가_아닌_한_자리_번호는_종전대로_찍는다():
    # C-41 본책 한 자리 복원 기본값(pm 10-07 · 10-10 판정)은 그대로다.
    assert _b("2 다음 글을 읽고 물음에 답하시오.").startswith("⠼⠃⠲⠀")
